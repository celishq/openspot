import XCTest
@testable import OpenspotCore

@MainActor
final class ClipboardReadTests: XCTestCase {
    private let clock = FakeClock()
    private let board = FakeClipboard()
    private var folder: URL!
    private var runs: SpotRuns!
    private var api: CommandAPI!

    override func setUp() async throws {
        folder = try temporaryFolder()
        runs = SpotRuns(clock: clock.value)
        runs.listen(to: board)
        api = CommandAPI(mac: Mac(clipboard: board), places: .test(["OPENSPOT_CONFIG": folder.path]), runs: runs)
    }

    private func call(_ arguments: [String]) async throws -> CommandAnswer {
        let request = CommandRequest(arguments: ["clipboard", "read"] + arguments, folder: folder.path)
        let work = try XCTUnwrap(api.work(for: try XCTUnwrap(api.call(of: request)), request: request, input: { "" }))
        return await work()
    }

    func testWithinPrintsACopyOnlyUntilItIsOlderThanTheSecondsSinceOpenspotFirstSawIt() async throws {
        board.copy("https://a.com/x\n")
        let fresh = try await call(["--within", "120"])
        clock.advance(by: 119)
        let late = try await call(["--within", "120"])
        clock.advance(by: 1)
        let old = try await call(["--within", "120"])
        let plain = try await call([])
        board.copy("two\nlines")
        let next = try await call(["--within", "120"])

        XCTAssertEqual([fresh.output, late.output, old.output, plain.output, next.output], ["https://a.com/x\n", "https://a.com/x\n", "", "https://a.com/x\n", "two\nlines"])
        XCTAssertEqual([fresh.code, old.code], [0, 0])
    }

    func testBlocksPrintEachKindOfCopyAsLinesOfItsKind() async throws {
        board.copy("two\nlines")
        let text = try await call(["--blocks"])
        board.copy("https://a.com/x\n")
        let link = try await call(["--blocks"])
        let files = [folder.appendingPathComponent("a.txt"), folder.appendingPathComponent("b.txt")]
        board.copy(files: files)
        let copied = try await call(["--blocks"])

        XCTAssertEqual(text.output, "text=two\\nlines\n")
        XCTAssertEqual(link.output, "url=https://a.com/x\n")
        XCTAssertEqual(copied.output, "file=\(files[0].path)\nfile=\(files[1].path)\n")
    }

    func testBlocksSaveAPictureToAFile() async throws {
        board.copy(image: Data([1, 2, 3]), kind: "png")

        let answer = try await call(["--blocks"])

        let block = try XCTUnwrap(TextBlock.blocks(in: answer.output).first)
        let picture = try XCTUnwrap(block.value("picture"))
        XCTAssertEqual(try Data(contentsOf: URL(fileURLWithPath: picture)), Data([1, 2, 3]))
        XCTAssertTrue(picture.hasSuffix(".png"), picture)
        XCTAssertEqual(block.value("title"), "Copied image")
    }

    func testBlocksPrintNothingForAPasswordOrAnEmptyText() async throws {
        board.copy(concealed: "hunter2")
        let password = try await call(["--blocks"])
        board.copy("  \n")
        let blank = try await call(["--blocks"])

        XCTAssertEqual([password.output, blank.output], ["", ""])
        XCTAssertEqual([password.code, blank.code], [0, 0])
    }

    func testBlocksPrintNothingForATextOverTheLimitOfAKeptFile() async throws {
        board.copy(String(repeating: "a", count: Int(Timeline.cloneLimit) + 1))
        let huge = try await call(["--blocks"])

        XCTAssertEqual(huge.output, "")
    }

    func testBlocksPrintNothingForACopyMarkedTransientOrAutoGenerated() async throws {
        board.copy("one-time code", marked: ["org.nspasteboard.TransientType"])
        let transient = try await call(["--blocks"])
        board.copy("generated", marked: ["org.nspasteboard.AutoGeneratedType"])
        let generated = try await call(["--blocks"])
        let plain = try await call([])

        XCTAssertEqual([transient.output, generated.output], ["", ""])
        XCTAssertEqual(plain.output, "generated")
    }

    func testBlocksTakeWithin() async throws {
        board.copy("fresh")
        let fresh = try await call(["--blocks", "--within", "60"])
        clock.advance(by: 61)
        let old = try await call(["--within", "60", "--blocks"])

        XCTAssertEqual([fresh.output, old.output], ["text=fresh\n", ""])
        XCTAssertEqual(CommandLineCall(arguments: ["clipboard", "read", "--blocks"])?.value as? ClipboardCall, .blocks(within: nil))
    }

    func testWithinTakesAnAgeAboveZeroInSecondsOrWithItsUnit() {
        for words in [["--within"], ["--within", "0"], ["--within", "0m"], ["--within", "soon"], ["--within", "2w"], ["--within", "5", "x"]] {
            XCTAssertNil(CommandLineCall(arguments: ["clipboard", "read"] + words)?.value as? ClipboardCall, words.joined(separator: " "))
        }
        let ages = ["120", "90s", "2m", "1h", "1d"].map { CommandLineCall(arguments: ["clipboard", "read", "--within", $0])?.value as? ClipboardCall }
        XCTAssertEqual(ages, [.read(within: 120), .read(within: 90), .read(within: 120), .read(within: 3_600), .read(within: 86_400)])
    }
}
